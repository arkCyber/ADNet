/**
 * Single-class entry point. Boot the handle, print the
 * node id, hash a small payload, resolve an IPNS name. If
 * the bindings are absent (this file compiled in isolation),
 * every call surfaces `AdnetError.Feature` — useful for CI
 * gating the binding-generation step.
 */
suspend fun runAdnetDemo(dataDir: String) {
    val vm = AdnetDemoViewModel(dataDir)
    vm.boot()
    // `boot()` is fire-and-forget on the internal scope;
    // wait until `state` settles into a terminal value
    // (Ready / Error) before reading it. The 30 s cap is
    // generous for a cold start on Android emulators.
    val settled = withTimeoutOrNull(BOOT_TIMEOUT_MS) {
        vm.state.first { it is State.Ready || it is State.Error }
    }
    when (val s = settled ?: vm.state.value) {
        is State.Ready -> println("booted: ${s.nodeId}")
        is State.Error -> println("error: ${s.error.message}")
        else           -> println("still booting…")
    }
    // Quick sanity: hash a 4-byte payload and confirm the
    // ticket is non-empty. We don't care about correctness
    // — only that the FFI round-trip succeeds.
    val info = vm.putBytes(byteArrayOf(1, 2, 3, 4))
    println("put: $info")
    val resolved = vm.resolve("a3net://example")
    println("resolve: $resolved")
    vm.shutdown()
}

private const val BOOT_TIMEOUT_MS = 30_000L
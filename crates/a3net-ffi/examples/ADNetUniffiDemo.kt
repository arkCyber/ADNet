/**
 * A3NetUniffiDemo.kt — Kotlin / Android consumer for the
 * uniffi surface of `a3net-ffi`.
 *
 * The companion Rust crate exposes a UDL at
 * `crates/a3net-ffi/src/a3net.udl` (generated by uniffi when
 * the `--features uniffi` build is active). Generate the
 * Kotlin bindings with:
 *
 *     cargo run -p a3net-ffi --features uniffi -- uniffi \
 *         generate src/a3net.udl --language kotlin \
 *         --out-dir bindings/kotlin
 *
 * The generated module declares `AdnetHandle`, `AdnetError`
 * and the record types. This file *demonstrates* how an
 * Android app would consume them: a coroutine-driven
 * `ViewModel`, a `StateFlow<State>` the UI subscribes to,
 * and `try { … } catch (e: AdnetError)` for the typed error
 * path.
 *
 * To keep this file standalone — compilable in any IDE that
 * points at the uniffi bindings — the bindings below are
 * declared as `expect object`/`expect class` placeholders.
 * The real classes are produced by `uniffi-bindgen` and live
 * next to this file at build time; simply delete the
 * placeholders and let the bindings take over.
 */


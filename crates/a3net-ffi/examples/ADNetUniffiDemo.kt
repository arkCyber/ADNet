sealed class AdnetError(message: String) : Throwable(message) {
    class InvalidArgument(message: String) : AdnetError(message)
    class InvalidUtf8(message: String) : AdnetError(message)
    class InvalidJson(message: String) : AdnetError(message)
    class Node(message: String) : AdnetError(message)
    class Runtime(message: String) : AdnetError(message)
    class Feature(message: String) : AdnetError(message)
    class Io(message: String) : AdnetError(message)
    class NotFound(message: String) : AdnetError(message)
    class Profile(message: String) : AdnetError(message)
}

data class BlobPutInfo(val hash: String, val ticket: String, val size: ULong)
data class BlobFetchInfo(val hash: String, val size: ULong)
data class IpnsPublishInfo(val name: String)
data class IpnsResolveInfo(val name: String, val value: String)
data class NodeInfo(val nodeId: String, val uptimeSecs: ULong)
data class NodeMetricsInfo(
    val peerCount: UInt,
    val blobCount: UInt,
    val gossipTopics: UInt,
    val uptimeSecs: ULong,
)

/**
 * Stub of the uniffi object. Replace with the
 * `uniffi-bindgen`-generated `AdnetHandle` once the bindings
 * are built. The shape mirrors the Rust source so any caller
 * can rely on the names.
 *
 * Note: the placeholder `gossipSubscribe` method from the
 * v0.1 demo was removed when the uniffi callback interface
 * machinery landed in a follow-up PR. Subscribe-style APIs
 * are exposed as top-level functions, e.g.
 * `a3netFfiPlaceholderGossipSubscribe(topic)`.
 */
expect class AdnetHandle(dataDir: String) {
    fun ensureBooted(): String
    fun nodeId(): String
    fun info(): NodeInfo
    fun putBytes(data: ByteArray): BlobPutInfo
    fun fetchTicket(ticket: String): BlobFetchInfo
    fun ipnsPublish(name: String, value: String): IpnsPublishInfo
    fun ipnsResolve(name: String): IpnsResolveInfo
    fun metrics(): NodeMetricsInfo
    fun destroy()
}

fun a3netVersion(): UInt = 0u

/**
 * Placeholder gossip subscription. Returns the topic name as a
 * stable subscription id until the full callback interface is
 * wired through `uniffi::CallbackInterface`. The Rust side
 * declares this as `a3net_ffi_placeholder_gossip_subscribe`.
 */
fun a3netFfiPlaceholderGossipSubscribe(topic: String): String =
    if (topic.isEmpty()) throw AdnetError.InvalidArgument("topic must not be empty")
    else "gossip::$topic"

// ---------------------------------------------------------------------------
// ViewModel — coroutine-driven, exposes StateFlow<State>
// ---------------------------------------------------------------------------

/**
 * State the UI can render. `Error` carries the typed
 * `AdnetError` so the activity can `when (state) { … }`
 * over the variants in a Kotlin-idiomatic way.
 */
sealed class State {
    object Idle : State()
    object Booting : State()
    data class Ready(val nodeId: String) : State()
    data class Error(val error: AdnetError) : State()
}

class AdnetDemoViewModel(dataDir: String) {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.Default)
    private val _state = MutableStateFlow<State>(State.Idle)
    val state: StateFlow<State> = _state.asStateFlow()

    private var handle: AdnetHandle? = null
    private val dir = dataDir

    fun boot() {
        scope.launch {
            _state.value = State.Booting
            try {
                val h = withContext(Dispatchers.IO) { AdnetHandle(dir) }
                val id = withContext(Dispatchers.IO) { h.ensureBooted() }
                handle = h
                _state.value = State.Ready(id)
            } catch (e: AdnetError) {
                _state.value = State.Error(e)
            }
        }
    }

    fun putBytes(data: ByteArray): Result<BlobPutInfo> =
        runOrError { handle?.putBytes(data) }

    fun resolve(name: String): Result<IpnsResolveInfo> =
        runOrError { handle?.ipnsResolve(name) }

    fun metrics(): Result<NodeMetricsInfo> =
        runOrError { handle?.metrics() }

    private inline fun <T> runOrError(block: () -> T?): Result<T> = try {
        val v = block() ?: return Result.failure(
            AdnetError.Runtime("node not booted"),
        )
        Result.success(v)
    } catch (e: AdnetError) {
        Result.failure(e)
    }

    fun shutdown() {
        scope.launch {
            try {
                handle?.destroy()
            } catch (_: AdnetError) {
                // best-effort: drop the handle silently.
            }
            handle = null
        }
    }
}

